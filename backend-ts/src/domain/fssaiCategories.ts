function looksLikeAdditiveLabel(name: string): boolean {
  const t = name.trim();
  if (!t) return true;
  if (/tartra|carmoisine|erythrosine|curcumin|canthaxanthin|phosphate|benzoate|sorbate|polysorb|allura|sunset/i.test(t)) {
    return true;
  }
  if (/^ins\s*\d/i.test(t) || /^\d{3,4}/.test(t)) return true;
  return t.split(/\s+/).length <= 2 && /^[A-Z][a-z]+$/.test(t) && t.length < 18;
}

export function resolveFoodCategoryName(
  code: string,
  storedName?: string | null
): string {
  const c = (code || "").trim();
  if (NAMES[c]) return NAMES[c];
  if (c) {
    const parts = c.split(".");
    while (parts.length > 1) {
      parts.pop();
      const parent = NAMES[parts.join(".")];
      if (parent) return parent;
    }
  }
  const stored = (storedName || "").trim();
  if (stored && !looksLikeAdditiveLabel(stored)) return stored;
  return c ? `Food category ${c}` : "Unspecified category";
}
