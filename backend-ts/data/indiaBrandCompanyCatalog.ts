/** Flatten empties and dedupe brand spellings per company. */
export function flattenIndiaBrandCompanyCatalog(): Array<{
  company: string;
  brand: string;
}> {
  const out: Array<{ company: string; brand: string }> = [];
  const seenBrand = new Set<string>();
  for (const [company, brands] of Object.entries(INDIA_BRAND_COMPANY_CATALOG)) {
    if (!brands.length) continue;
    // Skip placeholder keys that only exist as section markers
    if (company.toLowerCase().includes("already") || company.toLowerCase().includes("peers")) {
      continue;
    }
    for (const brand of brands) {
      const key = brand.trim().toLowerCase();
      if (!key || seenBrand.has(key)) continue;
      seenBrand.add(key);
      out.push({ company, brand: brand.trim() });
    }
  }
  return out;
}

export function listIndiaCompanies(): string[] {
  return Object.entries(INDIA_BRAND_COMPANY_CATALOG)
    .filter(
      ([company, brands]) =>
        brands.length > 0 &&
        !company.toLowerCase().includes("already") &&
        !company.toLowerCase().includes("peers")
    )
    .map(([company]) => company)
    .sort((a, b) => a.localeCompare(b));
}
