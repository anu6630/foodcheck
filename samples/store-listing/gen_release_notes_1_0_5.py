def validate(text: str) -> None:
    stack: list[str] = []
    for m in re.finditer(r"</?([A-Za-z0-9-]+)>", text):
        tag = m.group(0)
        name = m.group(1)
        if tag.startswith("</"):
            if not stack or stack[-1] != name:
                raise SystemExit(f"BAD close {tag}; stack={stack}")
            stack.pop()
        else:
            stack.append(name)
    if stack:
        raise SystemExit(f"unclosed: {stack}")


def main() -> None:
    assert set(ORDER) == set(NOTES), set(ORDER) ^ set(NOTES)
    chunks = [f"<{lang}>\n{NOTES[lang].strip()}\n</{lang}>" for lang in ORDER]
    text = "\n".join(chunks) + "\n"
    validate(text)

