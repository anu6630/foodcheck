def main() -> None:
    paths = [
        Path("/Volumes/SSDX 1/codes/foodcheck/samples/store-listing/play-release-notes.xml"),
        Path.home() / "Downloads/lifex-food-play-assets/play-release-notes.xml",
        Path.home() / "Downloads/play-release-notes.xml",
    ]
    for path in paths:
        text = path.read_text(encoding="utf-8")
        for loc, body in FIXES.items():
            assert "\ufffd" not in body, loc
            assert len(body) <= 500, (loc, len(body))
            pat = re.compile(rf"<{loc}>.*?</{loc}>", re.S)
            repl = f"<{loc}>\n{body}\n</{loc}>"
            text2, n = pat.subn(repl, text, count=1)
            if n != 1:
                raise RuntimeError(f"failed to replace {loc} in {path}")
            text = text2
        if "\ufffd" in text:
            raise RuntimeError(f"still has replacement chars: {path}")
        path.write_text(text, encoding="utf-8")
        print("fixed", path)


if __name__ == "__main__":
    main()
